# 1. Fetch latest changes from upstream
# git fetch upstream
#
# # 2. Switch to your main branch
# git checkout main
#
# # 3. Merge upstream/main into your fork’s main
# git merge upstream/main
#
# # 4. Push updated main to your fork
# git push origin main
#
# # 5. Switch to your custom branch
# git checkout unixmon-cli
#
# # 6. Rebase your custom branch onto the updated main
# git rebase main
#
# # 7. Push updated custom branch to your fork
# git push origin unixmon-cli --force
#
